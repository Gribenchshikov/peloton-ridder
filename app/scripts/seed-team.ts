function extFrom(url: string, contentType: string | null): { ext: string; type: string } {
  const fromHeader = contentType?.split(";")[0]?.trim() ?? "";
  if (fromHeader === "image/png") return { ext: "png", type: fromHeader };
  if (fromHeader === "image/webp") return { ext: "webp", type: fromHeader };
  if (fromHeader === "image/jpeg") return { ext: "jpg", type: fromHeader };
  if (url.endsWith(".png")) return { ext: "png", type: "image/png" };
  if (url.endsWith(".webp")) return { ext: "webp", type: "image/webp" };
  return { ext: "jpg", type: "image/jpeg" };
}

async function main() {
  const connectionString = process.env.DATABASE_URL;
  if (!connectionString) throw new Error("DATABASE_URL не задан");

  const photosDir = resolve(root, "../public/uploads/team");
  await mkdir(photosDir, { recursive: true });

  const prisma = new PrismaClient({ adapter: new PrismaPg({ connectionString }) });

  try {
    const rows = [];
    for (const [index, member] of TEAM.entries()) {
      const res = await fetch(member.photo);
      if (!res.ok) throw new Error(`Не удалось скачать фото ${member.name}: ${res.status}`);
      const buffer = Buffer.from(await res.arrayBuffer());
      const { ext } = extFrom(member.photo, res.headers.get("content-type"));
      const filename = `${randomUUID()}.${ext}`;
      await writeFile(resolve(photosDir, filename), buffer);
      rows.push({
        name: member.name,
        role: member.role,
        bio: member.bio,
        photoUrl: `/uploads/team/${filename}`,
        type: "TEAM" as const,
        order: index + 1,
      });
      console.log(`OK ${member.name}`);
    }

    await prisma.teamMember.deleteMany({ where: { type: "TEAM" } });
    await prisma.teamMember.createMany({ data: rows });
    console.log(`Импортировано участников: ${rows.length}`);
  } finally {
    await prisma.$disconnect();
  }
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
